def _quick_action_plists(label: str, shell_script: str, takes_folders: bool) -> tuple[bytes, bytes]:
    """Return (Info.plist, document.wflow) bytes for an Automator Quick Action."""
    service: dict = {
        "NSBackgroundColorName": "background",
        "NSIconName": "NSActionTemplate",
        "NSMenuItem": {"default": label},
        "NSMessage": "runWorkflowAsService",
        "NSRequiredContext": {"NSApplicationIdentifier": "com.apple.finder"},
    }
    if takes_folders:
        service["NSSendFileTypes"] = ["public.folder"]
    info = {"NSServices": [service]}

    input_type = "com.apple.Automator.fileSystemObject" if takes_folders else "com.apple.Automator.nothing"
    action = {
        "action": {
            "AMAccepts": {"Container": "List", "Optional": True, "Types": ["com.apple.cocoa.string"]},
            "AMActionVersion": "2.0.3",
            "AMApplication": ["Automator"],
            "AMParameterProperties": {
                "COMMAND_STRING": {},
                "CheckedForUserDefaultShell": {},
                "inputMethod": {},
                "shell": {},
                "source": {},
            },
            "AMProvides": {"Container": "List", "Types": ["com.apple.cocoa.string"]},
            "ActionBundlePath": "/System/Library/Automator/Run Shell Script.action",
            "ActionName": "Run Shell Script",
            "ActionParameters": {
                "COMMAND_STRING": shell_script,
                "CheckedForUserDefaultShell": True,
                "inputMethod": 1,  # pass input as arguments
                "shell": "/bin/bash",
                "source": "",
            },
            "BundleIdentifier": "com.apple.RunShellScript",
            "CFBundleVersion": "2.0.3",
            "CanShowSelectedItemsWhenRun": False,
            "CanShowWhenRun": True,
            "Category": ["AMCategoryUtilities"],
            "Class Name": "RunShellScriptAction",
            "InputUUID": str(uuid.uuid4()).upper(),
            "Keywords": ["Shell", "Script", "Command", "Run", "Unix"],
            "OutputUUID": str(uuid.uuid4()).upper(),
            "UUID": str(uuid.uuid4()).upper(),
            "UnlocalizedApplications": ["Automator"],
            "isViewVisible": True,
        }
    }
    workflow = {
        "AMApplicationBuild": "523",
        "AMApplicationVersion": "2.10",
        "AMDocumentVersion": "2",
        "actions": [action],
        "connectors": {},
        "workflowMetaData": {
            "applicationBundleIDsByPath": {},
            "applicationPaths": [],
            "inputTypeIdentifier": input_type,
            "outputTypeIdentifier": "com.apple.Automator.nothing",
            "presentationMode": 11,
            "processesInput": 0,
            "serviceInputTypeIdentifier": input_type,
            "serviceOutputTypeIdentifier": "com.apple.Automator.nothing",
            "serviceProcessesInput": 0,
            "systemImageName": "NSActionTemplate",
            "useAutomaticInputType": 0,
            "workflowTypeIdentifier": "com.apple.Automator.servicesMenu",
        },
    }
    return plistlib.dumps(info), plistlib.dumps(workflow)


class MacContextMenu:
    def __init__(self, services_dir: Optional[Path] = None, command: Optional[list[str]] = None) -> None:
        self.services_dir = services_dir or Path.home() / "Library" / "Services"
        self._command = command

    def _workflow(self, name: str) -> Path:
        return self.services_dir / f"{name}.workflow"

    def status(self) -> MenuStatus:
        installed = all((self._workflow(n) / "Contents" / "document.wflow").exists() for n in (MAC_FOLDER_ACTION, MAC_WINDOW_ACTION))
        return MenuStatus(True, installed, "Appears under Quick Actions in the right-click menu.")

    def install(self) -> None:
        command = " ".join(shlex.quote(part) for part in (self._command or launch_command()))
        folder_script = f'for f in "$@"; do {command} --dest "$f" >/dev/null 2>&1 & done'
        window_script = (
            'd=$(osascript -e \'tell application "Finder" to if (count of Finder windows) > 0 then '
            "POSIX path of (target of front Finder window as alias)')\n"
            '[ -z "$d" ] && d="$HOME/Desktop"\n'
            f'{command} --dest "$d" >/dev/null 2>&1 &'
        )
        for name, script, takes_folders in (
            (MAC_FOLDER_ACTION, folder_script, True),
            (MAC_WINDOW_ACTION, window_script, False),
        ):
            info, workflow = _quick_action_plists(name, script, takes_folders)
            contents = self._workflow(name) / "Contents"
            contents.mkdir(parents=True, exist_ok=True)
            (contents / "Info.plist").write_bytes(info)
            (contents / "document.wflow").write_bytes(workflow)
        self._refresh_services()

    def uninstall(self) -> None:
        import shutil

        for name in (MAC_FOLDER_ACTION, MAC_WINDOW_ACTION):
            shutil.rmtree(self._workflow(name), ignore_errors=True)
        self._refresh_services()

    @staticmethod
    def _refresh_services() -> None:
        try:
            subprocess.run(["/System/Library/CoreServices/pbs", "-flush"], check=False, timeout=10, capture_output=True)
        except (OSError, subprocess.SubprocessError):
            pass  # Finder picks the change up on its own, just a little later


