"""Add / remove a "New project here" entry in Windows Explorer and the macOS Finder.

Windows: per-user registry keys under ``HKCU\\Software\\Classes`` (no administrator rights).
    * right-click on empty space inside a folder   -> ``Directory\\Background\\shell``
    * right-click on a folder                      -> ``Directory\\shell``
  On Windows 11 the entry appears under "Show more options".

macOS: two Finder Quick Actions written to ``~/Library/Services``.
    * "New project here"            -> shown when a folder is selected
    * "New project in this window"  -> shown when right-clicking the window background
  The Quick Action files are generated by code and have not been verified on a real Mac yet;
  see README for the manual fallback.
"""

from __future__ import annotations

import plistlib
import shlex
import subprocess
import sys
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Optional, Protocol

APP_KEY = "ProjectStarter"
LABEL_BACKGROUND = "New project here"
LABEL_FOLDER = "New project inside this folder"
MAC_FOLDER_ACTION = "New project here"
MAC_WINDOW_ACTION = "New project in this window"


@dataclass(frozen=True)
class MenuStatus:
    supported: bool
    installed: bool
    detail: str = ""


def launch_command() -> list[str]:
    """Command line that starts this app: the frozen executable, or Python plus ``run.py``."""
    if getattr(sys, "frozen", False):
        return [sys.executable]
    launcher = Path(__file__).resolve().parents[3] / "run.py"
    interpreter = sys.executable
    if sys.platform == "win32" and interpreter.lower().endswith("python.exe"):
        pythonw = Path(interpreter).with_name("pythonw.exe")
        if pythonw.exists():
            interpreter = str(pythonw)  # no console window flashing up
    return [interpreter, str(launcher)]


# ---------------------------------------------------------------- Windows


class RegistryBackend(Protocol):
    def set_default(self, key_path: str, value: str) -> None: ...
    def set_value(self, key_path: str, name: str, value: str) -> None: ...
    def delete_tree(self, key_path: str) -> None: ...
    def exists(self, key_path: str) -> bool: ...


class WinRegistry:
    """The real registry (HKEY_CURRENT_USER). Only usable on Windows."""

    def __init__(self) -> None:
        import winreg  # imported lazily so other platforms can import this module

        self._winreg = winreg

    def set_default(self, key_path: str, value: str) -> None:
        with self._winreg.CreateKey(self._winreg.HKEY_CURRENT_USER, key_path) as key:
            self._winreg.SetValueEx(key, "", 0, self._winreg.REG_SZ, value)

    def set_value(self, key_path: str, name: str, value: str) -> None:
        with self._winreg.CreateKey(self._winreg.HKEY_CURRENT_USER, key_path) as key:
            self._winreg.SetValueEx(key, name, 0, self._winreg.REG_SZ, value)

    def delete_tree(self, key_path: str) -> None:
        winreg = self._winreg
        try:
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, key_path, 0, winreg.KEY_READ | winreg.KEY_WRITE) as key:
                while True:
                    try:
                        child = winreg.EnumKey(key, 0)
                    except OSError:
                        break
                    self.delete_tree(key_path + "\\" + child)
            winreg.DeleteKey(winreg.HKEY_CURRENT_USER, key_path)
        except FileNotFoundError:
            pass

    def exists(self, key_path: str) -> bool:
        try:
            with self._winreg.OpenKey(self._winreg.HKEY_CURRENT_USER, key_path):
                return True
        except FileNotFoundError:
            return False


class WindowsContextMenu:
    BACKGROUND_KEY = rf"Software\Classes\Directory\Background\shell\{APP_KEY}"
    FOLDER_KEY = rf"Software\Classes\Directory\shell\{APP_KEY}"

    def __init__(self, registry: Optional[RegistryBackend] = None, command: Optional[list[str]] = None) -> None:
        self._registry = registry
        self._command = command

    @property
    def registry(self) -> RegistryBackend:
        if self._registry is None:
            self._registry = WinRegistry()
        return self._registry

    def _command_line(self) -> str:
        command = self._command or launch_command()
        return subprocess.list2cmdline(command) + ' --dest "%V"'

    def status(self) -> MenuStatus:
        installed = self.registry.exists(self.BACKGROUND_KEY) and self.registry.exists(self.FOLDER_KEY)
        return MenuStatus(True, installed, "Appears under 'Show more options' on Windows 11.")

    def install(self) -> None:
        command_line = self._command_line()
        command = self._command or launch_command()
        for key, label in ((self.BACKGROUND_KEY, LABEL_BACKGROUND), (self.FOLDER_KEY, LABEL_FOLDER)):
            self.registry.set_default(key, label)
            if getattr(sys, "frozen", False):
                self.registry.set_value(key, "Icon", f'"{command[0]}",0')
            self.registry.set_default(key + r"\command", command_line)

    def uninstall(self) -> None:
        self.registry.delete_tree(self.BACKGROUND_KEY)
        self.registry.delete_tree(self.FOLDER_KEY)


