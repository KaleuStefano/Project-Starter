class UnsupportedContextMenu:
    def status(self) -> MenuStatus:
        return MenuStatus(False, False, "Right-click integration is available on Windows and macOS.")

    def install(self) -> None:
        raise NotImplementedError("Right-click integration is available on Windows and macOS.")

    def uninstall(self) -> None:
        raise NotImplementedError("Right-click integration is available on Windows and macOS.")


def get_context_menu():
    if sys.platform == "win32":
        return WindowsContextMenu()
    if sys.platform == "darwin":
        return MacContextMenu()
    return UnsupportedContextMenu()
